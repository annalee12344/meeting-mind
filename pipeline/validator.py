"""
Step 3 — Evidence validation via fuzzy string matching.

Verifies that all quotes extracted by the LLM genuinely exist within the
original raw meeting transcript using RapidFuzz partial string matching.
Sets evidence.verified = True/False accordingly, checks uniqueness of item IDs,
and marks parent items with needs_review = True if evidence is unverified or missing.
"""
import logging
from typing import Optional, Set
from rapidfuzz import fuzz

import config
from models.output import ResolvedResult, Evidence

logger = logging.getLogger(__name__)


class Validator:
    """
    Step 3 Validator: Validates evidence quotes and schema integrity.
    """

    def __init__(self, threshold: Optional[int] = None) -> None:
        """
        Initialize the Validator.

        Args:
            threshold: Fuzzy matching similarity threshold (0-100).
                       Defaults to config.FUZZY_MATCH_THRESHOLD.
        """
        self.threshold: int = (
            threshold if threshold is not None else config.FUZZY_MATCH_THRESHOLD
        )
        logger.debug(f"Validator initialized with fuzzy match threshold={self.threshold}")

    def verify_quote(self, quote: str, original_transcript: str) -> bool:
        """
        Check if a quote exists in the original transcript using fuzzy partial ratio.

        Args:
            quote: Quote string to search for.
            original_transcript: Raw or preprocessed transcript text.

        Returns:
            True if partial match score >= threshold, False otherwise.
        """
        if not quote or not quote.strip() or not original_transcript:
            return False

        clean_quote = quote.strip()
        clean_transcript = original_transcript.strip()

        # Compute match score, trying both case-sensitive and lower-case
        score_raw = fuzz.partial_ratio(clean_quote, clean_transcript)
        score_lower = fuzz.partial_ratio(clean_quote.lower(), clean_transcript.lower())
        best_score = max(score_raw, score_lower)

        matched = best_score >= self.threshold
        if not matched:
            logger.debug(
                f"Quote verification failed (score {best_score:.1f} < {self.threshold}): '{clean_quote}'"
            )
        return matched

    def validate(
        self,
        output: ResolvedResult,
        original_transcript: str,
    ) -> ResolvedResult:
        """
        Validate all evidence in ResolvedResult against the original transcript.

        Performs:
        1. Fuzzy match on every Evidence quote -> sets evidence.verified
        2. If all evidence for an item is unverified (or missing), marks item.needs_review = True
        3. Validates that item_ids are unique across all categories
        4. Validates that required fields are non-empty

        Args:
            output: MeetingOutput generated by Step 2 Resolver.
            original_transcript: Original raw transcript text.

        Returns:
            MeetingOutput with verified flags and review warnings updated.
        """
        seen_ids: Set[str] = set()
        total_evidence = 0
        verified_evidence = 0

        # Helper to validate a list of evidence objects
        def validate_evidence_list(ev_list: list[Evidence]) -> tuple[int, int]:
            nonlocal total_evidence, verified_evidence
            item_total = len(ev_list)
            item_verified = 0
            for ev in ev_list:
                total_evidence += 1
                is_valid = self.verify_quote(ev.quote, original_transcript)
                ev.verified = is_valid
                if is_valid:
                    verified_evidence += 1
                    item_verified += 1
            return item_total, item_verified

        # Helper to check item ID uniqueness
        def check_id_uniqueness(item_id: str, item_type: str) -> bool:
            if not item_id or not item_id.strip():
                logger.warning(f"Empty item_id in {item_type}")
                return False
            if item_id in seen_ids:
                logger.warning(f"Duplicate item_id '{item_id}' detected in {item_type}")
                return False
            seen_ids.add(item_id)
            return True

        # 1. Validate Decisions
        for decision in output.decisions:
            id_ok = check_id_uniqueness(decision.item_id, "Decision")
            if not id_ok or not decision.topic.strip() or not decision.final_value.strip():
                decision.needs_review = True

            dec_total_ev = 0
            dec_verified_ev = 0
            for entry in decision.history:
                tot, ver = validate_evidence_list(entry.evidence)
                dec_total_ev += tot
                dec_verified_ev += ver

            # Mark needs_review if no evidence exists or NONE of the evidence is verified
            if dec_total_ev == 0 or dec_verified_ev == 0:
                decision.needs_review = True

        # 2. Validate Action Items
        for ai in output.action_items:
            id_ok = check_id_uniqueness(ai.item_id, "ActionItem")
            if not id_ok or not ai.task.strip():
                ai.needs_review = True

            # If assignee is missing or ambiguous, flag for human review
            if not ai.assignee or not ai.assignee.strip() or ai.assignee.strip().lower() in ("unknown", "chưa rõ", "chưa phân công", "chưa giao"):
                ai.needs_review = True

            tot, ver = validate_evidence_list(ai.evidence)
            if tot == 0 or ver == 0:
                ai.needs_review = True

        # 3. Validate Blockers
        for blocker in output.blockers:
            id_ok = check_id_uniqueness(blocker.item_id, "Blocker")
            if not id_ok or not blocker.issue.strip():
                blocker.needs_review = True

            tot, ver = validate_evidence_list(blocker.evidence)
            if tot == 0 or ver == 0:
                blocker.needs_review = True

        # 4. Validate Requests
        for req in output.requests:
            id_ok = check_id_uniqueness(req.item_id, "Request")
            if not id_ok or not req.content.strip():
                req.needs_review = True

            tot, ver = validate_evidence_list(req.evidence)
            if tot == 0 or ver == 0:
                req.needs_review = True

        # 5. Validate Unresolved Items
        for ui in output.unresolved_items:
            id_ok = check_id_uniqueness(ui.item_id, "UnresolvedItem")
            if not id_ok or not ui.topic.strip() or not ui.reason_unresolved.strip():
                ui.needs_review = True

            tot, ver = validate_evidence_list(ui.evidence)
            if tot == 0 or ver == 0:
                ui.needs_review = True

        logger.info(
            f"[Step 3] Validation complete: {verified_evidence}/{total_evidence} "
            f"evidence quotes verified ({self.threshold}% fuzzy threshold)."
        )

        return output
