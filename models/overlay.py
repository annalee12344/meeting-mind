"""
User Overlay and View Models for Meeting Mind.

Represents the mutable user layer decoupled from the immutable AI layer:
- AI layer (MeetingOutput): Generated by analysis pipeline; immutable ground truth.
- User Overlay (MeetingOverlay): Granular modifications made by users (edits, status changes,
  deletions, manual tasks, conversions, notes).
- View Models (MeetingViewModel, ViewTask, ViewUnresolvedItem, ViewIssue): Merged models
  consumed by UI, designed as if a database existed.
- Export Package (ExportPackage): Complete serialization for export/import including both layers.
"""
from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional
from uuid import uuid4

from pydantic import BaseModel, Field

from models.output import (
    Evidence,
    IssueNote,
    MeetingOutput,
    PublicDecision,
    PublicIssue,
    PublicMeta,
    PublicTask,
    PublicUnresolvedItem,
    generate_uuid,
)


class TaskOverlay(BaseModel):
    """User modifications to an individual task."""
    title: Optional[str] = None
    assignee: Optional[str] = None
    deadline_raw: Optional[str] = None
    deadline_iso: Optional[str] = None
    status: Optional[Literal["open", "done"]] = None
    completed_at: Optional[str] = None
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class UnresolvedOverlay(BaseModel):
    """User modifications to an unresolved item."""
    status: Optional[Literal["open", "converted"]] = None
    suggested_assignee: Optional[str] = None
    suggested_deadline_raw: Optional[str] = None
    suggested_deadline_iso: Optional[str] = None
    converted_to_task_id: Optional[str] = None
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class IssueOverlay(BaseModel):
    """User modifications to an issue."""
    status: Optional[Literal["open", "resolved"]] = None
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class ViewTask(BaseModel):
    """
    Task domain view model (as if backed by a Tasks database table).
    Combines AI-extracted fields with user overlay state.
    """
    id: str = Field(default_factory=generate_uuid, description="Stable UUID")
    meeting_id: str = Field(default="", description="ID of the associated meeting")
    source_ref: Optional[str] = Field(default=None, description="Original LLM reference ID, e.g. A001")
    title: str
    assignee: Optional[str] = None
    assigned_by: Optional[str] = None
    requested_by: Optional[str] = None
    deadline_raw: Optional[str] = None
    deadline_iso: Optional[str] = None
    status: Literal["open", "done"] = "open"
    source: Literal["ai", "manual", "from_unresolved"] = "ai"
    evidence: list[Evidence] = Field(default_factory=list)
    needs_review: bool = False
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    completed_at: Optional[str] = None


class ViewUnresolvedItem(BaseModel):
    """
    UnresolvedItem domain view model.
    Combines AI unresolved topics with user overlay.
    """
    id: str = Field(default_factory=generate_uuid, description="Stable UUID")
    meeting_id: str = Field(default="", description="ID of the associated meeting")
    source_ref: Optional[str] = None
    kind: Literal["open_decision", "unconfirmed_task"]
    content: str
    reason_unresolved: Optional[str] = None
    suggested_assignee: Optional[str] = None
    suggested_deadline_raw: Optional[str] = None
    suggested_deadline_iso: Optional[str] = None
    status: Literal["open", "converted"] = "open"
    evidence: list[Evidence] = Field(default_factory=list)
    needs_review: bool = False


class ViewIssue(BaseModel):
    """
    Issue domain view model.
    Combines AI blockers with user overlay and per-user notes.
    """
    id: str = Field(default_factory=generate_uuid, description="Stable UUID")
    meeting_id: str = Field(default="", description="ID of the associated meeting")
    source_ref: Optional[str] = None
    content: str
    owner: Optional[str] = None
    status: Literal["open", "resolved"] = "open"
    evidence: list[Evidence] = Field(default_factory=list)
    notes: list[IssueNote] = Field(default_factory=list)
    needs_review: bool = False


class MeetingOverlay(BaseModel):
    """
    User overlay document stored per meeting/transcript.
    Contains all user-applied customizations and manual additions.
    """
    schema_version: str = "2.0.0"
    meeting_id: str = Field(description="Unique meeting ID or transcript hash")
    transcript_hash: Optional[str] = None
    tasks: Dict[str, TaskOverlay] = Field(
        default_factory=dict, description="Task modifications indexed by Task UUID"
    )
    manual_tasks: List[ViewTask] = Field(
        default_factory=list, description="Manually created user tasks"
    )
    deleted_task_ids: List[str] = Field(
        default_factory=list, description="IDs of tasks deleted by user"
    )
    unresolved: Dict[str, UnresolvedOverlay] = Field(
        default_factory=dict, description="Unresolved modifications indexed by UUID"
    )
    deleted_unresolved_ids: List[str] = Field(
        default_factory=list, description="IDs of unresolved items deleted by user"
    )
    issues: Dict[str, IssueOverlay] = Field(
        default_factory=dict, description="Issue modifications indexed by UUID"
    )
    issue_notes: List[IssueNote] = Field(
        default_factory=list, description="User notes on issues"
    )
    deleted_issue_ids: List[str] = Field(
        default_factory=list, description="IDs of issues deleted by user"
    )
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class MeetingViewModel(BaseModel):
    """
    Merged meeting output combining AI pipeline results with user overlay.
    This is the single model used by all UI components.
    """
    meeting_id: str
    summary: str
    participants: list[str] = Field(default_factory=list)
    decisions: list[PublicDecision] = Field(default_factory=list)
    tasks: list[ViewTask] = Field(default_factory=list)
    unresolved: list[ViewUnresolvedItem] = Field(default_factory=list)
    issues: list[ViewIssue] = Field(default_factory=list)
    meta: PublicMeta = Field(default_factory=PublicMeta)
    overlay: MeetingOverlay = Field(default_factory=lambda: MeetingOverlay(meeting_id=""))


class ExportPackage(BaseModel):
    """
    Standard JSON format for exporting and importing meetings,
    bundling the immutable AI result alongside the user overlay.
    """
    schema_version: str = "2.0.0"
    exported_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    meeting_name: str = "Meeting Mind Analysis"
    transcript: Optional[str] = None
    result: MeetingOutput
    overlay: MeetingOverlay
